// 한 MBTI 유형의 정보 — 결과 화면(MbtiResult)이 소비하는 형태
export interface MbtiInfo {
  code: MbtiCode; // 4글자 코드
  nickname: string; // 별칭
  summary: string; // 요약 문단
  traits: string[]; // 핵심 특징 항목

  // 확장 필드 (TASK 1)
  catchphrase: string; // 히어로 캐치프레이즈
  color: { name: string; hex: string }; // 시그니처 색상
  axes: {
    e: number; // E(외향) 방향 0~100 (높을수록 E)
    n: number; // N(직관) 방향 0~100 (높을수록 N)
    t: number; // T(사고) 방향 0~100 (높을수록 T)
    j: number; // J(판단) 방향 0~100 (높을수록 J)
  };
  oneLine: string; // 한줄 성격 요약
  strengths: string[]; // 강점 3~4개
  weaknesses: string[]; // 약점 3~4개
  stress: string; // 스트레스 반응
  growth: string; // 성장 포인트
  loveStyle: string; // 연애 스타일
  friendStyle: string; // 우정 스타일
  careers: string[]; // 어울리는 직업 3~5개
  compatible: MbtiCode[]; // 잘 맞는 유형 2~3개
  incompatible: MbtiCode[]; // 안 맞는 유형 1~2개
  memes: string[]; // 공감 짤 문구 3~4개
  celebrities: string[]; // 유명인/캐릭터 3~4명
  memberCount: number; // mock 멤버 수
}

